const provider = new AndroidPackageProvider();

/** dex2jar and Vineflower are host tools; without admitted installs these cases are skipped. */
const TOOLS = await Promise.all([resolveVineflower(), resolveDex2jar()]).then(
  () => true,
  () => false,
);

const decompile = async (
  input: Record<string, unknown>,
): Promise<DexDecompilation> => {
  const result = await provider.decompileClass(
    decompileDexClassInputSchema.parse(input),
  );
  if (!result.ok) throw result.error;
  return dexDecompilationSchema.parse(result.value);
};

describe("dex2jar error reports and jar sets", () => {
  it("reads failed methods and whole-file failures from the text report", () => {
    const text = [
      "#This file is generated by dex2jar",
      "There are 1 fails.",
      "There are 2 methods fail to translate.",
      "",
      "================= 0 ===================",
      "Lcom/example/A;->run(I)V",
      "java.lang.RuntimeException: boom",
      "",
      "================= 1 ===================",
      "Lcom/example/A$B;-><init>(Lcom/example/A;)V",
    ].join("\n");
    expect(parseDex2jarErrors(text)).toEqual({
      methods: [
        { owner: "Lcom/example/A;", name: "run", descriptor: "(I)V" },
        {
          owner: "Lcom/example/A$B;",
          name: "<init>",
          descriptor: "(Lcom/example/A;)V",
        },
      ],
      fileFailures: 1,
    });
  });

  it("reports a jar symlink to a directory as unavailable", async () => {
    const lib = await mkdtemp(join(tmpdir(), "rea-dex2jar-link-"));
    try {
      await mkdir(join(lib, "directory"));
      await symlink(join(lib, "directory"), join(lib, "bad.jar"));
      await expect(jarSetDigest(lib)).rejects.toMatchObject({
        _tag: "Dex2jarUnavailable",
      });
    } finally {
      await removeTestWorkspace(lib);
    }
  });

  it("digests a jar set so any other set is not admitted", async () => {
    const lib = await realpath(
      await mkdtemp(join(await realpath(tmpdir()), "rea-dex2jar-set-")),
    );
    try {
      const digest = await jarSetDigest(lib);
      expect(digest.jars).toEqual([]);
      expect(ADMITTED_DEX2JAR_SETS.map((set) => set.sha256)).not.toContain(
        digest.sha256,
      );
    } finally {
      await removeTestWorkspace(lib);
    }
  });
});

let root: string;
let fixtures: AndroidFixtures;

beforeAll(async () => {
  if (ANDROID_TOOLS === null || !TOOLS) return;
  root = await realpath(
    await mkdtemp(join(await realpath(tmpdir()), "rea-dex-decompile-")),
  );
  fixtures = await buildAndroidFixtures(root);
}, 180_000);
afterAll(async () => {
  if (root) await removeTestWorkspace(root);
});

describe.skipIf(ANDROID_TOOLS === null || !TOOLS)(
  "dex2jar + Vineflower reconstruction over d8-built DEX files",
  () => {
    it("decompiles a class from a bare DEX without overstating the method-name check", async () => {
      const report = await decompile({
        path: fixtures.dex,
        class: "com.example.oops.DataProvider",
      });
      expect(report.class).toEqual({
        descriptor: "Lcom/example/oops/DataProvider;",
        name: "com.example.oops.DataProvider",
      });
      expect(report.selection.basis).toBe("file");
      expect(report.top_level).toBe("com/example/oops/DataProvider");
      expect(report.source).toMatchObject({
        file: "com/example/oops/DataProvider.java",
        confidence: "inferred",
        media_type: "text/x-java; charset=utf-8",
        derived_from: [report.selection.dex_sha256],
      });
      expect(report.source.text).toMatch(
        /public class DataProvider extends ContentProvider/u,
      );
      expect(report.converter).toMatchObject({
        id: "dex2jar",
        version: "2.4",
        lib: { set_sha256: ADMITTED_DEX2JAR_SETS[0]?.sha256 },
      });
      expect(report.decompiler).toMatchObject({
        id: "vineflower",
        version: "1.12.0",
      });
      expect(report.checks).toEqual([
        expect.objectContaining({ id: "dex2jar_translated", state: "passed" }),
        expect.objectContaining({ id: "vineflower_clean", state: "passed" }),
        expect.objectContaining({
          id: "methods_present",
          state: "not_checked",
        }),
      ]);
      expect(report.missing_methods).toEqual([]);
      expect(report.untrusted_methods).toEqual([]);
      expect(report.coverage).toEqual([
        expect.objectContaining({ facet: "reconstruct", state: "partial" }),
      ]);
    });

    it("keeps the text but reports partial when Vineflower cannot decompile a method", async () => {
      const report = await decompile({
        path: fixtures.libraryDex,
        class: "org.oops.lib.Codes",
      });
      // d8 lowers the synchronized method so Vineflower cannot rebuild its finally block.
      expect(report.checks.map((check) => [check.id, check.state])).toEqual([
        ["dex2jar_translated", "passed"],
        ["vineflower_clean", "failed"],
        ["methods_present", "not_checked"],
      ]);
      expect(report.decompiler_notes).toEqual([
        expect.objectContaining({ text: "// $VF: Couldn't be decompiled" }),
      ]);
      expect(report.messages.join("\n")).toMatch(
        /describe .* couldn't be decompiled/u,
      );
      expect(report.messages.join("\n")).not.toMatch(
        /oopsware-(dex2jar|vineflower)-/u,
      );
      expect(report.source.text).toMatch(/public Codes\(long /u);
      expect(report.coverage[0]).toMatchObject({
        facet: "reconstruct",
        state: "partial",
      });
    });

    it("finds a class in the APK's second DEX and derives the text from that DEX only", async () => {
      const report = await decompile({
        path: fixtures.apk,
        class: "org.oops.lib.Codes",
      });
      expect(report.selection).toMatchObject({
        container: null,
        entry: "classes2.dex",
        basis: "only",
      });
      expect(report.source.derived_from).toEqual([report.selection.dex_sha256]);
      const bundled = await decompile({
        path: fixtures.aab,
        class: "org.oops.lib.Codes",
      });
      expect(bundled.selection).toMatchObject({
        entry: "base/dex/classes2.dex",
        dex_sha256: report.selection.dex_sha256,
      });
      expect(bundled.source.sha256).toBe(report.source.sha256);
    });

    it("decompiles the outermost class when a nested class is selected", async () => {
      const report = await decompile({
        path: fixtures.dex,
        class: "com.example.oops.R$string",
      });
      expect(report.class.descriptor).toBe("Lcom/example/oops/R$string;");
      expect(report.top_level).toBe("com/example/oops/R");
      expect(report.classes.map((entry) => [entry.name, entry.role])).toEqual(
        expect.arrayContaining([
          ["com/example/oops/R$string", "selected"],
          ["com/example/oops/R", "outer"],
        ]),
      );
      expect(report.source.file).toBe("com/example/oops/R.java");
      expect(report.source.text).toMatch(/class string\b/u);
    });

    it("refuses a class no DEX file defines", async () => {
      const result = await provider.decompileClass(
        decompileDexClassInputSchema.parse({
          path: fixtures.dex,
          class: "com.example.Missing",
        }),
      );
      expect(result.ok).toBe(false);
      if (!result.ok) expect(result.error._tag).toBe("AnalysisInputError");
    });

    it("refuses source over max_source_bytes rather than cutting it", async () => {
      const result = await provider.decompileClass(
        decompileDexClassInputSchema.parse({
          path: fixtures.libraryDex,
          class: "org.oops.lib.Codes",
          max_source_bytes: 16,
        }),
      );
      expect(result.ok).toBe(false);
      if (!result.ok)
        expect(result.error._tag).toBe("AnalysisResourceConstraintError");
    });
  },
);

describe.skipIf(ANDROID_TOOLS === null || !TOOLS)(
  "dex2jar review regressions",
  () => {
    it("rechecks a cached jar set and runs only its verified private copy", async () => {
      const tool = await resolveDex2jar();
      const lib = join(root, "copied-dex2jar");
      const jars = await stageDex2jar(tool, lib);
      expect((await jarSetDigest(lib)).sha256).toBe(tool.setSha256);
      const cached = { ...tool, lib, jars };
      await writeFile(jars[0]!, "changed after discovery");
      await expect(
        convertDex({
          dex: new Uint8Array(),
          tool: cached,
          java: "/no/java",
          heapMib: 64,
          timeoutMs: 2000,
        }),
      ).rejects.toMatchObject({
        _tag: "Dex2jarUnavailable",
        message: expect.stringContaining("jar set changed"),
      });
      await writeFile(join(lib, "added.jar"), "extra classpath entry");
      await expect(
        stageDex2jar(cached, join(root, "extra-jar-check")),
      ).rejects.toMatchObject({ _tag: "Dex2jarUnavailable" });
    });

    it("maps a missing Java executable to a typed unavailable error", async () => {
      await expect(
        convertDex({
          dex: new Uint8Array(),
          tool: await resolveDex2jar(),
          java: join(root, "missing-java"),
          heapMib: 64,
          timeoutMs: 2000,
        }),
      ).rejects.toMatchObject({ _tag: "Dex2jarUnavailable" });
    });
  },
);
