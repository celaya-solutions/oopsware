/** Main header tag names, as rpm's rpmtag.h names them (1000 → "name"). */
export const RPM_TAGS: ReadonlyMap<number, string> = new Map(
  MAIN_TAGS.map(([tag, name]) => [tag, name]),
);

/** Signature header tag names (1004 → "md5", 269 → "sha1"). */
export const RPM_SIGNATURE_TAGS: ReadonlyMap<number, string> = new Map(
  SIGNATURE_TAGS.map(([tag, name]) => [tag, name]),
);

/** Declared data type per main header tag, where rpmtag.h declares one. */
export const RPM_TAG_TYPES: ReadonlyMap<number, RpmValueType> = new Map(
  MAIN_TAGS.flatMap(([tag, , type]) =>
    type === null ? [] : [[tag, type] as const],
  ),
);

/** Declared data type per signature header tag. */
export const RPM_SIGNATURE_TAG_TYPES: ReadonlyMap<number, RpmValueType> =
  new Map(
    SIGNATURE_TAGS.flatMap(([tag, , type]) =>
      type === null ? [] : [[tag, type] as const],
    ),
  );

export type RpmHeaderKind = "signature" | "main";

/** Tag name for display: rpmtag.h's name, or the number when rpm has none. */
export const rpmTagName = (tag: number, kind: RpmHeaderKind): string =>
  (kind === "signature" ? RPM_SIGNATURE_TAGS : RPM_TAGS).get(tag) ??
  `tag ${String(tag)}`;
