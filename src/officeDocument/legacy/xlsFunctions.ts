export interface BuiltinFunction {
  readonly name: string;
  /** The argument count of a fixed function; null when the count varies. */
  readonly args: number | null;
}

export const FUNCTIONS: ReadonlyMap<number, BuiltinFunction> = new Map(
  FTAB.split(/\s+/u)
    .filter((entry) => entry !== "")
    .map((entry): [number, BuiltinFunction] => {
      const [index = "", name = "", args = "v"] = entry.split(":");
      return [
        Number.parseInt(index, 10),
        { name, args: args === "v" ? null : Number.parseInt(args, 10) },
      ];
    }),
);

export const COMMANDS: ReadonlyMap<number, string> = new Map(
  CETAB.split(/\s+/u)
    .filter((entry) => entry !== "")
    .map((entry): [number, string] => {
      const [index = "", name = ""] = entry.split(":");
      return [Number.parseInt(index, 16), name];
    }),
);
