// Regenerates src/python/bytecode/profileData.ts from installed CPython
// interpreters: each one reports its own opcode tables through
// scripts/python/bytecode-profile.py (run with -I, nothing else imported).
// Usage: node scripts/python/write-bytecode-profiles.mjs /path/python3.13 ...
// A profile is only admitted after the real-producer lane passes for it.
import { execFile } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const exec = promisify(execFile);
const repository = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const dumper = join(repository, "scripts/python/bytecode-profile.py");
const target = join(repository, "src/python/bytecode/profileData.ts");

const interpreters = process.argv.slice(2);
if (interpreters.length === 0) {
  console.error("usage: write-bytecode-profiles.mjs PYTHON...");
  process.exit(2);
}

const profiles = [];
for (const python of interpreters) {
  const { stdout } = await exec(python, ["-I", dumper], { env: {} });
  const raw = JSON.parse(stdout);
  // Only real instruction bytes (0-255); pseudo-instructions never reach a .pyc.
  const opcodes = Object.fromEntries(
    Object.entries(raw.opcodes).filter(([, code]) => code < 256),
  );
  const real = new Set(Object.values(opcodes));
  const sets = Object.fromEntries(
    Object.entries(raw.sets).map(([key, codes]) => [
      key,
      codes.filter((code) => real.has(code)),
    ]),
  );
  profiles.push({
    version: raw.version,
    release: raw.release,
    magic: raw.magic,
    marshal_version: raw.marshal_version,
    opcodes,
    has_argument: raw.has_argument,
    hasarg: raw.hasarg?.filter((code) => real.has(code)) ?? null,
    cache: raw.cache,
    sets,
    cmp_op: raw.cmp_op,
    nb_ops: raw.nb_ops,
    intrinsic_1: raw.intrinsic_1,
    intrinsic_2: raw.intrinsic_2,
    common_constants: raw.common_constants,
    special_methods: raw.special_methods,
    function_attr_flags: raw.function_attr_flags,
    make_function_flags: raw.make_function_flags,
    format_value_converters: raw.format_value_converters,
    code_flags: raw.code_flags,
    unicode_version: raw.unicode_version,
    printable: raw.printable,
  });
}
profiles.sort((left, right) => left.magic - right.magic);

const header = `// Generated by scripts/python/write-bytecode-profiles.mjs from each
// interpreter's own opcode, dis and importlib modules. Do not edit by hand.
import type { BytecodeProfileData } from "./profileTypes.js";

export const BYTECODE_PROFILE_DATA: readonly BytecodeProfileData[] = `;
// One profile per line keeps the long printable-range lists readable in diffs.
await writeFile(
  target,
  `${header}[\n${profiles.map((profile) => JSON.stringify(profile)).join(",\n")}\n];\n`,
);
console.log(
  `wrote ${String(profiles.length)} profiles: ${profiles.map((p) => `${p.release} (magic ${String(p.magic)})`).join(", ")}`,
);
